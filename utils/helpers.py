import streamlit as st
import pandas as pd
from fpdf import FPDF


def safe_read_csv(uploaded_file, required_columns):
    """Reads a CSV safely. Shows a friendly message instead of a raw error
    if the file is invalid or missing required columns."""
    try:
        df = pd.read_csv(uploaded_file)
    except Exception:
        st.error("⚠️ This file couldn't be read. Please upload a valid CSV file.")
        return None

    missing = [c for c in required_columns if c not in df.columns]
    if missing:
        st.error(f"⚠️ This file is missing required column(s): {', '.join(missing)}. "
                  f"Please check the format and try again.")
        return None
    return df


